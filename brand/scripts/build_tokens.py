"""Generate CSS variables from the brand's JSON source; no dependencies."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOKENS = json.loads((ROOT / "tokens.json").read_text())


def declarations(section, prefix):
    return [f"  --lm-{prefix}-{key}: {value};" for key, value in section.items()]


def theme_values(theme):
    return [f"  --lm-{key}: {TOKENS['color'].get(value, value)};" for key, value in theme.items()]


def build():
    lines = ["/* Generated by scripts/build_tokens.py. Edit tokens.json. */"]
    for name, file, weight, style in [
        ("Instrument Serif", "InstrumentSerif-Regular.woff2", "400", "normal"),
        ("Instrument Serif", "InstrumentSerif-Italic.woff2", "400", "italic"),
        ("Geist", "Geist-Variable.woff2", "100 900", "normal"),
        ("Geist Mono", "GeistMono-Variable.woff2", "100 900", "normal"),
    ]:
        lines.append(f"@font-face {{ font-family: '{name}'; src: url('./fonts/{file}') format('woff2'); font-weight: {weight}; font-style: {style}; font-display: swap; }}")
    lines.append(":root {")
    for section in ["color", "font", "type", "space", "radius", "motion", "layout"]:
        lines.extend(declarations(TOKENS[section], section))
    lines.extend(theme_values(TOKENS["theme"]["light"]))
    lines.append("  color-scheme: light;\n}")
    lines.append('[data-lm-theme="dark"] {')
    lines.extend(theme_values(TOKENS["theme"]["dark"]))
    lines.append("  color-scheme: dark;\n}")
    lines.append("@media (prefers-reduced-motion: reduce) { :root { --lm-motion-fast: 0ms; --lm-motion-normal: 0ms; } }\n")
    (ROOT / "tokens.css").write_text("\n".join(lines))


if __name__ == "__main__":
    build()
