#!/usr/bin/env bash
# Writes languages/lemma/highlights.scm from the Tree-sitter grammar's
# highlights.scm, renaming the captures Zed's themes name differently. Zed
# styles a capture by its longest prefix among the theme's names, as Neovim
# does, and lets a later pattern override an earlier one, so the rest carry
# over unchanged.
#
# Usage: editors/zed/update-highlights.sh [output]
#
# editors/check.sh fails when the committed copy is out of date.

set -euo pipefail

zed_directory=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
source_query="$zed_directory/../tree-sitter-lemma/queries/highlights.scm"
output=${1:-$zed_directory/languages/lemma/highlights.scm}

{
  echo "; Generated by editors/zed/update-highlights.sh from"
  echo "; editors/tree-sitter-lemma/queries/highlights.scm; edit that file instead."
  echo
  sed -E \
    -e 's/@character\.special/@punctuation.special/g' \
    -e 's/@variable\.builtin/@variable.special/g' \
    -e 's/ @spell//g' \
    "$source_query"
} >"$output"
