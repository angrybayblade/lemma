"""Lemma's adapter for FastAPI apps: it imports the app and writes the
OpenAPI document FastAPI generates for it.

    LEMMA_OUTPUT=<file> LEMMA_ENTRY=<module>[:<attribute>] python fastapi_openapi.py

Run with the app's interpreter, from the directory its imports start at.
Without an attribute, every FastAPI app the module defines at its top level
is included. Each operation carries `x-lemma-handler`: the file and line of
the function handling it.
"""

import importlib
import inspect
import json
import os
import sys


def main():
    output = os.environ.get("LEMMA_OUTPUT")
    entry = os.environ.get("LEMMA_ENTRY", "")
    root = os.path.abspath(os.environ.get("LEMMA_ROOT", os.getcwd()))
    if not output or not entry:
        print("LEMMA_OUTPUT and LEMMA_ENTRY are required", file=sys.stderr)
        return 2
    # Imports start where the app's do, not beside this adapter.
    adapter_directory = os.path.dirname(os.path.abspath(__file__))
    sys.path[:] = [path for path in sys.path if os.path.abspath(path or ".") != adapter_directory]
    sys.path.insert(0, os.getcwd())
    from fastapi import FastAPI
    from fastapi.routing import APIRoute

    module_name, _, attribute = entry.partition(":")
    module = importlib.import_module(module_name)
    if attribute:
        apps = [getattr(module, attribute)]
    else:
        apps = [value for value in vars(module).values() if isinstance(value, FastAPI)]
    if not apps:
        print(f"lemma: {entry} defines no FastAPI app", file=sys.stderr)
        return 3
    document = {"openapi": "3.0.0", "info": {"title": "generated by Lemma", "version": "0"},
                "paths": {}, "components": {}, "x-lemma-unread": []}
    for app in apps:
        part = app.openapi()
        routes = list(api_routes(app.routes, APIRoute))
        for path, item in part.get("paths", {}).items():
            for method, operation in item.items():
                route = route_of(routes, path, method, operation.get("operationId", ""))
                handler = handler_of(route.endpoint, root) if route else None
                if handler:
                    operation["x-lemma-handler"] = handler
                document["paths"].setdefault(path, {})[method] = operation
        for kind, entries in part.get("components", {}).items():
            document["components"].setdefault(kind, {}).update(entries)
    with open(output, "w") as file:
        json.dump(document, file, indent=2)
    print(f"lemma: {len(document['paths'])} paths from {len(apps)} apps", file=sys.stderr)
    return 0


def api_routes(routes, route_type):
    """Every route in `routes` and the routers included in them, however
    the FastAPI version holds an included router."""
    for route in routes:
        if isinstance(route, route_type):
            yield route
        for nested in (getattr(route, "routes", None), getattr(getattr(route, "original_router", None), "routes", None)):
            if nested:
                yield from api_routes(nested, route_type)


def route_of(routes, path, method, operation_id):
    """The route serving a document's operation: the same method, a path the
    document's ends with (prefixes are added on inclusion), and a function
    whose name starts FastAPI's operationId for it. None unless one fits."""
    fitting = [
        route for route in routes
        if method.upper() in route.methods
        and path.endswith(route.path_format)
        and operation_id.startswith(route.name)
    ]
    longest = max((len(route.path_format) for route in fitting), default=0)
    fitting = [route for route in fitting if len(route.path_format) == longest]
    return fitting[0] if len(fitting) == 1 else None


def handler_of(function, root):
    """`file:line` of the function handling a route, relative to `root`."""
    function = inspect.unwrap(function)
    try:
        file = inspect.getsourcefile(function)
        _, line = inspect.getsourcelines(function)
    except (OSError, TypeError):
        return None
    return f"{os.path.relpath(file, root)}:{line}"


if __name__ == "__main__":
    sys.exit(main())
