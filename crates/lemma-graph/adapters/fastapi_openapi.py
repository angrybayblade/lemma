"""Lemma's adapter for FastAPI apps: it imports the app and writes the
OpenAPI document FastAPI generates for it. The protocol is in
docs/adapters.md.

    LEMMA_OUTPUT=<file> LEMMA_ENTRY=<entries, one per line> python fastapi_openapi.py

Run with the app's interpreter, from the directory its imports start at.
An entry is `module:attribute`, the attribute an app or a function making
one (`create_app`), or a module alone, whose top-level apps are all read.
Apps mounted inside an app (`app.mount("/v2", v2)`) are read under their
mount path. Each operation carries `x-lemma-handler`: the file and line of
the function handling it.
"""

import importlib
import inspect
import json
import os
import sys


def main():
    output = os.environ.get("LEMMA_OUTPUT")
    entries = [line.strip() for line in os.environ.get("LEMMA_ENTRY", "").splitlines() if line.strip()]
    root = os.path.realpath(os.environ.get("LEMMA_ROOT", os.getcwd()))
    if not output or not entries:
        print("LEMMA_OUTPUT and LEMMA_ENTRY are required", file=sys.stderr)
        return 2
    # Imports start where the app's do, not beside this adapter.
    adapter_directory = os.path.dirname(os.path.abspath(__file__))
    sys.path[:] = [path for path in sys.path if os.path.abspath(path or ".") != adapter_directory]
    sys.path.insert(0, os.getcwd())
    from fastapi import FastAPI

    document = {"openapi": "3.0.0", "info": {"title": "generated by Lemma", "version": "0"},
                "paths": {}, "components": {}}
    unread = []
    for entry in entries:
        module_name, _, attribute = entry.partition(":")
        module = importlib.import_module(module_name)
        outside = outside_root(module, root)
        if outside:
            print(f"lemma: {module_name} was imported from {outside}, not from the code being read; "
                  "install the checkout itself, or put its source first on PYTHONPATH", file=sys.stderr)
            return 4
        for app in apps_of(module, attribute, FastAPI):
            for prefix, mounted in [("", app), *mounted_apps(app, FastAPI)]:
                try:
                    part = mounted.openapi()
                except Exception as error:  # noqa: BLE001 - any failure leaves the app unread
                    unread.append({"module": entry, "reason": f"could not describe the app at {prefix or '/'}: {error}"})
                    continue
                add_part(document, part, prefix, list(api_routes(mounted.routes)), root)
    document["x-lemma-unread"] = unread
    document["x-lemma-complete"] = not unread
    with open(output, "w") as file:
        json.dump(document, file, indent=2)
    count = sum(len(item) for item in document["paths"].values())
    print(f"lemma: {count} operations from {len(entries)} entries", file=sys.stderr)
    if count == 0:
        print(f"lemma: {', '.join(entries)} define no FastAPI routes", file=sys.stderr)
        return 3
    return 0


def outside_root(module, root):
    """Where `module` was imported from, if not from under `root`: an
    installed copy of the code, which at a past commit is today's code."""
    file = getattr(module, "__file__", None)
    if not file:
        return None
    path = os.path.realpath(file)
    return None if path.startswith(root + os.sep) else path


def apps_of(module, attribute, app_type):
    """The apps an entry names: its attribute, called if it makes the app,
    or every app the module defines at its top level."""
    if not attribute:
        return [value for value in vars(module).values() if isinstance(value, app_type)]
    value = getattr(module, attribute)
    if not isinstance(value, app_type) and callable(value):
        value = value()
    return [value] if isinstance(value, app_type) else []


def mounted_apps(app, app_type, prefix=""):
    """The apps mounted inside `app`, with their full mount paths."""
    from starlette.routing import Mount

    for route in app.routes:
        if isinstance(route, Mount) and isinstance(route.app, app_type):
            path = (prefix + route.path).rstrip("/")
            yield path, route.app
            yield from mounted_apps(route.app, app_type, path)


def add_part(document, part, prefix, routes, root):
    """Adds one app's document under its mount path, each operation tagged
    with its handler."""
    for path, item in part.get("paths", {}).items():
        for method, operation in item.items():
            if not isinstance(operation, dict):
                continue
            route = route_of(routes, path, method, operation.get("operationId") or "")
            handler = handler_of(route.endpoint, root) if route else None
            if handler:
                operation["x-lemma-handler"] = handler
            document["paths"].setdefault(prefix + path, {})[method] = operation
    for kind, entries in part.get("components", {}).items():
        document["components"].setdefault(kind, {}).update(entries)


def route_of(routes, path, method, operation_id):
    """The route serving a document's operation: the same method and the
    longest route path the document's path ends with (an included router's
    prefix is part of the route's path, a mount's is not). Several such
    routes are told apart by the operationId FastAPI gave the route, or one
    starting with its function's name. None unless one fits."""
    fitting = [route for route in routes if method.upper() in route.methods and path.endswith(route.path_format)]
    longest = max((len(route.path_format) for route in fitting), default=0)
    fitting = [route for route in fitting if len(route.path_format) == longest]
    if len(fitting) > 1:
        fitting = [
            route for route in fitting
            if operation_id in (route.operation_id, getattr(route, "unique_id", None))
            or operation_id.startswith(route.name)
        ]
    return fitting[0] if len(fitting) == 1 else None


def api_routes(routes):
    """Every route in `routes` and the routers included in them, however
    the FastAPI version holds an included router; not those of mounted
    apps, which are read on their own."""
    from fastapi.routing import APIRoute
    from starlette.routing import Mount

    for route in routes:
        if isinstance(route, APIRoute):
            yield route
        if isinstance(route, Mount):
            continue
        for nested in (getattr(route, "routes", None), getattr(getattr(route, "original_router", None), "routes", None)):
            if nested:
                yield from api_routes(nested)


def handler_of(function, root):
    """`file:line` of the function handling a route, relative to `root`;
    None for a function outside it, such as a library's."""
    function = inspect.unwrap(function)
    try:
        file = os.path.realpath(inspect.getsourcefile(function))
        _, line = inspect.getsourcelines(function)
    except (OSError, TypeError):
        return None
    if not file.startswith(root + os.sep):
        return None
    return f"{os.path.relpath(file, root)}:{line}"


if __name__ == "__main__":
    sys.exit(main())
