"""Lemma's adapter for Flask apps: it imports the app and writes an
OpenAPI document listing the routes in its URL map. Flask knows routes but
not their schemas, so the document says so with `x-lemma-schemas: false`
and the committed documents keep parameters, bodies and responses. The
protocol is in docs/adapters.md.

    LEMMA_OUTPUT=<file> LEMMA_ENTRY=<entries, one per line> python flask_routes.py

Run with the app's interpreter, from the directory its imports start at.
An entry is `module:attribute`, the attribute an app, a function making one
(`create_app`), or a werkzeug `DispatcherMiddleware`; or a module alone,
whose top-level apps are all read. Blueprints, nested blueprints and
`add_url_rule` are read through the URL map, which holds every rule at the
path it is served at. Flask apps mounted with `DispatcherMiddleware`, on
the entry or on an app's `wsgi_app`, are read under their mount path. Each
operation carries `x-lemma-handler`: the file and line of the view function,
or of the class-based view's method for that HTTP method.
"""

import importlib
import inspect
import json
import os
import re
import sys

# `<id>`, `<int:id>`, `<path:rest>`, `<any(a, b):kind>` all name one segment.
RULE_VARIABLE = re.compile(r"<(?:[^<>:]+:)?([A-Za-z_][A-Za-z0-9_]*)>")


def main():
    output = os.environ.get("LEMMA_OUTPUT")
    entries = [line.strip() for line in os.environ.get("LEMMA_ENTRY", "").splitlines() if line.strip()]
    root = os.path.realpath(os.environ.get("LEMMA_ROOT", os.getcwd()))
    if not output or not entries:
        print("LEMMA_OUTPUT and LEMMA_ENTRY are required", file=sys.stderr)
        return 2
    # Imports start where the app's do, not beside this adapter.
    adapter_directory = os.path.dirname(os.path.abspath(__file__))
    sys.path[:] = [path for path in sys.path if os.path.abspath(path or ".") != adapter_directory]
    sys.path.insert(0, os.getcwd())

    operations = []
    unread = []
    for entry in entries:
        module_name, _, attribute = entry.partition(":")
        module = importlib.import_module(module_name)
        outside = outside_root(module, root)
        if outside:
            print(f"lemma: {module_name} was imported from {outside}, not from the code being read; "
                  "install the checkout itself, or put its source first on PYTHONPATH", file=sys.stderr)
            return 4
        for served in apps_of(module, attribute):
            for prefix, app in served_apps(served, "", entry, unread):
                operations.extend(operations_of(app, prefix, root))
    document = {
        "openapi": "3.0.0",
        "info": {"title": "generated by Lemma", "version": "0"},
        "paths": paths_of(distinct(operations)),
        "x-lemma-schemas": False,
        "x-lemma-unread": unread,
        "x-lemma-complete": not unread,
    }
    with open(output, "w") as file:
        json.dump(document, file, indent=2, sort_keys=True)
    count = sum(len(item) for item in document["paths"].values())
    print(f"lemma: {count} operations from {len(entries)} entries", file=sys.stderr)
    if count == 0:
        print(f"lemma: {', '.join(entries)} define no Flask routes", file=sys.stderr)
        return 3
    return 0


def outside_root(module, root):
    """Where `module` was imported from, if not from under `root`: an
    installed copy of the code, which at a past commit is today's code."""
    file = getattr(module, "__file__", None)
    if not file:
        return None
    path = os.path.realpath(file)
    return None if path.startswith(root + os.sep) else path


def is_servable(value):
    """Whether `value` is something an entry can name directly: a Flask app
    or a dispatcher mounting apps."""
    from flask import Flask
    from werkzeug.middleware.dispatcher import DispatcherMiddleware

    return isinstance(value, (Flask, DispatcherMiddleware))


def apps_of(module, attribute):
    """The apps an entry names: its attribute, called if it makes the app,
    or every app the module defines at its top level that no other one
    mounts, since a mounted app is served only under its mount path."""
    if not attribute:
        return top_level_apps([value for value in vars(module).values() if is_servable(value)])
    value = getattr(module, attribute)
    if not is_servable(value) and callable(value) and not inspect.isclass(value):
        value = value()
    return [value] if is_servable(value) else []


def top_level_apps(values):
    """`values` without the apps another of them serves, by identity."""
    mounted = set()
    for value in values:
        for prefix, app in served_apps(value, "", "", []):
            if app is not value:
                mounted.add(id(app))
    roots = [value for value in values if id(value) not in mounted]
    return roots or values


def served_apps(wsgi, prefix, entry, unread, inside=()):
    """The Flask apps `wsgi` serves, each with the path it is mounted at:
    the app itself, and apps mounted through `DispatcherMiddleware` on it
    or on its `wsgi_app`. A mounted WSGI app that is not Flask is listed in
    `unread`, since its routes cannot be seen. `inside` holds what is being
    walked, so an app mounted inside itself is read once."""
    from flask import Flask
    from werkzeug.middleware.dispatcher import DispatcherMiddleware

    if id(wsgi) in inside:
        return
    inside = (*inside, id(wsgi))
    if isinstance(wsgi, Flask):
        yield prefix, wsgi
        if not is_own_wsgi_app(wsgi):
            yield from served_apps(wsgi.wsgi_app, prefix, entry, unread, inside)
        return
    owner = getattr(wsgi, "__self__", None)
    if isinstance(owner, Flask) and getattr(wsgi, "__name__", "") == "wsgi_app":
        yield from served_apps(owner, prefix, entry, unread, inside)
        return
    if isinstance(wsgi, DispatcherMiddleware):
        yield from served_apps(wsgi.app, prefix, entry, unread, inside)
        for mount, mounted in sorted(wsgi.mounts.items()):
            yield from served_apps(mounted, (prefix + mount).rstrip("/"), entry, unread, inside)
        return
    # Middleware such as ProxyFix keeps the app it wraps as `.app`.
    wrapped = getattr(wsgi, "app", None)
    if wrapped is not None and callable(wrapped):
        yield from served_apps(wrapped, prefix, entry, unread, inside)
        return
    name = getattr(wsgi, "__qualname__", type(wsgi).__qualname__)
    reason = f"the WSGI app at {prefix or '/'}, {name}, is not a Flask app, so its routes are not seen"
    item = {"module": entry, "reason": reason}
    if item not in unread:
        unread.append(item)


def is_own_wsgi_app(app):
    """Whether `app.wsgi_app` is still Flask's own, unwrapped."""
    wsgi_app = app.wsgi_app
    return getattr(wsgi_app, "__self__", None) is app and getattr(wsgi_app, "__name__", "") == "wsgi_app"


def operations_of(app, prefix, root):
    """One `(path, method, endpoint, handler)` per method of each rule in
    `app`'s URL map, under `prefix`, leaving out static files and the
    methods Flask adds by itself."""
    operations = []
    for rule in app.url_map.iter_rules():
        view = app.view_functions.get(rule.endpoint)
        if is_static(rule, view):
            continue
        path = prefix + openapi_path(rule.rule)
        for method in sorted(declared_methods(rule)):
            handler = handler_of(view_for_method(view, method), root) if view else None
            operations.append((path, method.lower(), rule.endpoint, handler))
    return operations


def is_static(rule, view):
    """Whether `rule` serves the app's or a blueprint's static files."""
    if rule.endpoint == "static":
        return True
    return getattr(view, "__name__", "") == "send_static_file"


def declared_methods(rule):
    """The methods a rule was registered for: without the `HEAD` werkzeug
    adds beside `GET`, and without the `OPTIONS` Flask answers by itself."""
    methods = set(rule.methods or ())
    if "GET" in methods:
        methods.discard("HEAD")
    if getattr(rule, "provide_automatic_options", False):
        methods.discard("OPTIONS")
    return methods


def openapi_path(rule):
    """A Flask rule as an OpenAPI path: `/users/<int:id>` is `/users/{id}`."""
    return RULE_VARIABLE.sub(r"{\1}", rule)


def view_for_method(view, method):
    """What handles `method` for a view: a class-based view's method of
    that name, else its class; a plain view function itself."""
    view_class = getattr(view, "view_class", None)
    if view_class is None:
        return view
    named = getattr(view_class, method.lower(), None)
    if named is None and method == "HEAD":
        named = getattr(view_class, "get", None)
    return named or view_class


def distinct(operations):
    """`operations` once each, in a fixed order: an app reached through
    two entries is read twice."""
    def order(operation):
        return tuple(part or "" for part in operation)

    return sorted(set(operations), key=order)


def paths_of(operations):
    """The OpenAPI `paths` for `operations`. An operation is named after its
    endpoint, with the method added when the endpoint serves several, and
    left unnamed when even that is shared, so Lemma names it by its path."""
    by_endpoint = {}
    for _, method, endpoint, _ in operations:
        by_endpoint.setdefault(endpoint, []).append(method)
    paths = {}
    for path, method, endpoint, handler in operations:
        methods = by_endpoint[endpoint]
        operation = {"responses": {"default": {"description": ""}}}
        if len(methods) == 1:
            operation["operationId"] = endpoint
        elif methods.count(method) == 1:
            operation["operationId"] = f"{endpoint}_{method}"
        if handler:
            operation["x-lemma-handler"] = handler
        paths.setdefault(path, {})[method] = operation
    return paths


def handler_of(function, root):
    """`file:line` of the function or class handling a route, relative to
    `root`; None for one outside it, such as a library's."""
    function = inspect.unwrap(function)
    try:
        file = os.path.realpath(inspect.getsourcefile(function))
        _, line = inspect.getsourcelines(function)
    except (OSError, TypeError):
        return None
    if not file.startswith(root + os.sep):
        return None
    return f"{os.path.relpath(file, root)}:{line}"


if __name__ == "__main__":
    sys.exit(main())
