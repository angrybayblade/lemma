// Lemma's adapter for Hono apps built with @hono/zod-openapi: it imports
// the app's route modules and writes the OpenAPI document their routes
// describe, as the framework itself would generate it.
//
// Run with bun from the directory whose node_modules hold the app's
// packages:
//   LEMMA_OUTPUT=<file> LEMMA_ENTRY=<dir or file>[:<dir or file>...] bun run hono-zod-openapi.ts
//
// Every route an OpenAPIHono router registers, in any module under the
// entries, is recorded where the framework registers it
// (OpenAPIRegistry.registerPath), so no app-level registry or script is
// needed. Each operation carries `x-lemma-handler`: the file and line that
// registered it. Modules that fail to import and routes that cannot be
// described are listed in the document's `x-lemma-unread` and on stderr;
// with no route at all, the adapter fails.

import { readdirSync, statSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { join, relative, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const output = process.env.LEMMA_OUTPUT
const entries = (process.env.LEMMA_ENTRY ?? '').split(':').filter(Boolean)
const root = resolve(process.env.LEMMA_ROOT ?? process.cwd())
if (!output || entries.length === 0) {
  console.error('LEMMA_OUTPUT and LEMMA_ENTRY are required')
  process.exit(2)
}

// The framework's own modules, resolved as the app resolves them, so the
// registry patched here is the one the app's routers use.
const fromApp = createRequire(join(resolve(entries[0]), 'package.json'))
const honoPath = fromApp.resolve('@hono/zod-openapi')
const fromHono = createRequire(honoPath)
const zodToOpenapi = await import(pathToFileURL(fromHono.resolve('@asteasolutions/zod-to-openapi')).href)

type Recorded = { route: Record<string, unknown>; file?: string; line?: number }
const recorded: Recorded[] = []
const registerPath = zodToOpenapi.OpenAPIRegistry.prototype.registerPath
zodToOpenapi.OpenAPIRegistry.prototype.registerPath = function (route: Record<string, unknown>) {
  recorded.push({ route, ...registeredAt(new Error().stack ?? '') })
  return registerPath.call(this, route)
}

// The first frame outside node_modules and this adapter: where the app
// registered the route.
function registeredAt(stack: string): { file?: string; line?: number } {
  for (const frame of stack.split('\n').slice(1)) {
    const match = frame.match(/\(?((?:file:\/\/)?\/[^():]+):(\d+):\d+\)?\s*$/)
    if (!match) continue
    const file = match[1].replace(/^file:\/\//, '')
    if (file.includes('/node_modules/') || file.endsWith('hono-zod-openapi.ts')) continue
    return { file: relative(root, file), line: Number(match[2]) }
  }
  return {}
}

function modules(entry: string): string[] {
  const path = resolve(entry)
  if (statSync(path).isFile()) return [path]
  const found: string[] = []
  for (const name of readdirSync(path).sort()) {
    if (name === 'node_modules' || name.startsWith('.')) continue
    const child = join(path, name)
    if (statSync(child).isDirectory()) {
      found.push(...modules(child))
    } else if (/\.(ts|tsx|js|mjs)$/.test(name) && !/\.(test|spec|d)\.|__tests__/.test(child)) {
      found.push(child)
    }
  }
  return found
}

const unread: string[] = []
for (const module of entries.flatMap(modules)) {
  try {
    await import(pathToFileURL(module).href)
  } catch (error) {
    const reason = `could not import ${relative(root, module)}: ${(error as Error).message?.split('\n')[0]}`
    unread.push(reason)
    console.error(`lemma: ${reason}`)
  }
}

// Each route is described on its own, so one schema the generator cannot
// describe (a z.lazy without OpenAPI metadata) loses only its route.
const document: Record<string, any> = {
  openapi: '3.0.0',
  info: { title: 'generated by Lemma', version: '0' },
  paths: {},
  components: {},
  'x-lemma-unread': unread,
}
for (const { route, file, line } of recorded) {
  let part
  try {
    part = new zodToOpenapi.OpenApiGeneratorV3([{ type: 'route', route }]).generateDocument({
      openapi: '3.0.0',
      info: { title: '', version: '0' },
    })
  } catch (error) {
    const reason = `could not describe ${(route.method as string).toUpperCase()} ${route.path}: ${(error as Error).message}`
    unread.push(reason)
    console.error(`lemma: ${reason}`)
    continue
  }
  for (const [path, item] of Object.entries(part.paths ?? {})) {
    for (const [method, operation] of Object.entries(item as Record<string, any>)) {
      if (file) operation['x-lemma-handler'] = `${file}:${line}`
      document.paths[path] = { ...document.paths[path], [method]: operation }
    }
  }
  for (const [kind, entries] of Object.entries(part.components ?? {})) {
    document.components[kind] = { ...document.components[kind], ...(entries as object) }
  }
}
writeFileSync(output, JSON.stringify(document, null, 2))
console.error(`lemma: ${recorded.length} routes from ${entries.length} entries; ${unread.length} things could not be read`)
if (recorded.length === 0) {
  console.error(`lemma: no route was registered${unread.length ? `; first: ${unread[0]}` : ''}`)
  process.exit(3)
}
process.exit(0)
